/*
 * Regenerates docs/what-we-can-record.md — the plain-English list Addie reads to
 * answer the one question no test can: is anything sold today that has no row?
 *
 * Run:  node docs/build-what-we-can-record.js
 *
 * ⚠ THE STRUCTURE IS READ OUT OF js/options.js, NOT TYPED HERE. Only the prose is
 * written by hand, because "how many feet of roofline you are lighting" cannot be
 * derived from a field name. Everything a machine can know — which options exist,
 * what each is called, what sets the price, and where each answer has to reach — is
 * taken from the registry every time this runs.
 *
 * ⚠ AND IT REFUSES RATHER THAN DRIFTING. If the registry gains or loses an option,
 * the prose here no longer covers it, and a list that quietly omits a real option is
 * worse than no list — it would read as a complete answer to the exact question it is
 * meant to help her ask. So a mismatch is a hard stop naming what to write.
 */

const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const src = fs.readFileSync(path.join(root, 'js', 'options.js'), 'utf8');

/* ---- read the registry ---------------------------------------------------- */
const options = src.split(/\n\s*\{\s*\n?\s*id:/).slice(1).map(b => ({
  id: (b.match(/^\s*'([^']+)'/) || [])[1],
  label: (b.match(/label:\s*'([^']*)'/) || [])[1] || '',
  affectsPrice: /affectsPrice:\s*true/.test(b),
  consumers: ((b.match(/consumers:\s*\[([^\]]*)\]/s) || [])[1] || '')
    .split(',').map(s => s.replace(/['\s]/g, '')).filter(Boolean),
})).filter(o => o.id);

/* ---- the prose, and ONLY the prose ---------------------------------------- */
const PROSE = {
  measuredFeet:       ['How many feet of roofline you are lighting.', 'the quote form'],
  lightsDescription:  ['Which colours, and the order if they alternate.', 'the quote form and the member portal'],
  wireColor:          ['White or green wire.', 'the quote form and the member portal'],
  outletTimer:        ['Whether they want a timer on the outlet.', 'the quote form and the member portal'],
  useEaves:           ['Whether we may use an outlet up in the eaves.', 'the quote form'],
  specificOutlet:     ['Which specific outlet to plug into, in their words.', 'the quote form, and picked out of the Misc column on the master sheet'],
  gateCode:           ['The code to get in.', 'the quote form, and picked out of Misc and Notes on the master sheet'],
  houseSides:         ['How many sides are lit — 1, 2, 3 or 4.', 'the quote form and the member portal'],
  installPreference:  ['When they want it hung — October, November, before Thanksgiving, or a named day.', 'the quote form and the master sheet'],
  notes:              ['Anything standing that is always true about the house.', 'the quote form and the office'],
  oneTimeNote:        ['Something true for this visit only.', 'the office'],
  wantsMailedInvoice: ['Whether they want the bill posted rather than emailed.', 'the quote form'],
  numberOfBins:       ['How many bins their lights fill. Worked out from the feet, never asked.', 'derived — one bin per 260 ft'],
  difficulty:         ['How hard the house is to do.', 'the office'],
};

/* ⚠ A HARD STOP, NOT A SHRUG. See the header: a list that silently omits a real
   option reads as a complete answer to the question it exists to help her ask. */
const ids = options.map(o => o.id);
const undocumented = ids.filter(i => !PROSE[i]);
const stale = Object.keys(PROSE).filter(i => !ids.includes(i));
if (undocumented.length || stale.length) {
  console.error('\n  This generator is out of step with js/options.js.\n');
  undocumented.forEach(i => console.error('    NEW option with no plain-English line:  ' + i));
  stale.forEach(i => console.error('    line here for an option that is GONE:    ' + i));
  console.error('\n  Add or remove the line in PROSE above, in the same commit that');
  console.error('  changed the registry, then run this again.\n');
  process.exit(1);
}

/* ---- where each answer goes, in her words rather than field names ---------- */
const PLACE = {
  quote: 'Quote', confirmation: 'Confirmation', customer: 'Customer record',
  crewSheet: 'Crew sheet', pullList: 'Warehouse pull list', invoice: 'Invoice',
  routes: 'Routes', schedule: 'Schedule',
};

const out = [];
out.push('# What the software can record about a customer');
out.push('');
out.push('**Generated from `js/options.js` by `docs/build-what-we-can-record.js`.**');
out.push('Do not edit this file — change the registry, or the prose in that script, and');
out.push('run it again. It refuses to generate if the two disagree.');
out.push('');
out.push('## Why this list exists');
out.push('');
out.push('Q-007 asked what the real option set was. That is answered: these fourteen,');
out.push('derived from the code and corrected by Addie on 2026-08-21, with');
out.push('`options-audit.test.js` holding them in place.');
out.push('');
out.push('What is **still open**, and can only ever be answered by Addie, is the question');
out.push('underneath it: **is anything sold today that has no row here at all?**');
out.push('');
out.push('⚠ **No test can find that one.** Every check in this repo works by comparing a');
out.push('declared option against the artifacts it has to reach — so an option nobody ever');
out.push('declared cannot fail anything. It is invisible by construction, permanently, and');
out.push('the only detector is somebody who knows the business reading the list.');
out.push('');
out.push('Two things that are **not** open, recorded so they are not asked again:');
out.push('');
out.push('- **What sets the price.** Only measured feet. Sides raise a re-quote because the');
out.push('  FOOTAGE changes; they are not a second price input (`houseSides.affectsPrice`).');
out.push('- **Where each answer must reach.** Frozen in the AGREED map in');
out.push('  `options-audit.test.js`. That changes when she changes her mind, not otherwise.');
out.push('');
out.push('---');
out.push('');
out.push('## The ' + options.length);
out.push('');

options.forEach(o => {
  const [what, asked] = PROSE[o.id];
  out.push('### ' + o.label);
  out.push('');
  out.push(what);
  out.push('');
  out.push('- **Asked at:** ' + asked);
  out.push('- **Sets the price:** ' + (o.affectsPrice
    ? 'Yes — this is the only thing that does'
    : (o.id === 'houseSides' ? 'No, only through the feet' : 'No')));
  out.push('- **Has to reach:** ' +
    o.consumers.map(c => PLACE[c] || c).join(' · '));
  out.push('');
});

out.push('---');
out.push('');
out.push('## How to read it');
out.push('');
out.push('Go down the list once and ask one thing of each: *is this something we sell, or');
out.push('something we ask?* Then the harder one: **what do we sell that is not on here?**');
out.push('');
out.push('Anything missing is not broken — it is absent. Nothing will complain, no test');
out.push('will fail, and it will simply never appear on a quote, a crew sheet or a pull');
out.push('list. That is what makes the ten minutes of reading worth it.');
out.push('');

fs.writeFileSync(path.join(root, 'docs', 'what-we-can-record.md'), out.join('\n'));
console.log('docs/what-we-can-record.md — ' + options.length + ' options, generated from the registry');

/* ---------------------------------------------------------------------------
 * AND THE SAME LIST AS A PAGE SHE CAN READ ANYWHERE.
 *
 * ⚠ BUILT FROM THE SAME `options` ARRAY, deliberately. Two hand-kept renderings of
 * one list is exactly the drift this repo spends its time preventing — and the one
 * nobody looks at is the one that goes wrong. The grouping below is DERIVED from
 * where each answer comes from, not typed: an option the customer never sees
 * (bins, difficulty, the one-time note) is a different kind of thing from one they
 * are asked, and that distinction is the useful half of the list.
 * ------------------------------------------------------------------------- */
const askedOfCustomer = o => !/^(the office|derived)/.test(PROSE[o.id][1]);
const GROUPS = [
  ['What the customer tells us',
   'Asked on the quote form, in the member portal, or read off the master sheet.',
   options.filter(askedOfCustomer)],
  ['What we work out ourselves',
   'Never asked. The customer does not see these and cannot set them.',
   options.filter(o => !askedOfCustomer(o))],
];

const esc = s => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;')
  .replace(/>/g, '&gt;').replace(/"/g, '&quot;');

const card = o => {
  const [what] = PROSE[o.id];
  const price = o.affectsPrice;
  return `      <article class="opt${price ? ' opt--price' : ''}">
        <header class="opt__head">
          <h3 class="opt__name">${esc(o.label)}</h3>
          <code class="opt__id">${esc(o.id)}</code>
        </header>
        <p class="opt__what">${esc(what)}</p>
        ${price ? '<p class="opt__price">Sets the price — the only one that does</p>' : ''}
        <p class="opt__reach"><span class="opt__reachLabel">Has to reach</span>
          ${o.consumers.map(c => `<span class="chip">${esc(PLACE[c] || c)}</span>`).join('\n          ')}
        </p>
      </article>`;
};

